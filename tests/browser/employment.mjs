import assert from 'node:assert/strict';
import {expect} from '@playwright/test';

export async function verifyEmployment(page, baseURL, locale, output) {
  async function read(id = '') {
    return page.evaluate(async id => {
      const response = await fetch(`/api/salary-projection?start_year=2026&end_year=2027${id ? `&scenario_id=${id}` : ''}`);
      assertResponse(response);
      return response.json();
      function assertResponse(response) {if (!response.ok) throw new Error('Synthetic projection read failed');}
    }, id);
  }
  const rows = model => model.people.map(person => ({id: person.id, actuals: person.actuals, projection: person.projection}));
  await page.goto(`${baseURL}/salary-projection`);
  await expect(page.locator('#salary-tabs button')).not.toHaveCount(0);
  await page.waitForFunction(() => document.querySelector('main').getAttribute('aria-busy') === 'false');
  const original = await read();
  const personId = original.people.find(person => person.projection.some(row => row.year === 2027)).id;
  await page.locator(`#salary-tabs [data-person-key="${personId}"]`).click();
  await expect(page.locator('[name="default_raise"]')).toHaveValue(String(Number(original.people.find(person => person.id === personId).settings.default_raise) * 100));
  for (const width of [1280, 390, 320]) {
    await page.setViewportSize({width, height: 1000});
    await expect(page.locator('[data-summary-span]').first()).toHaveAttribute('colspan', width <= 640 ? '3' : '4');
    await page.locator('.fv-navigation').evaluate(node => {node.open = false;});
    await expect(page.locator('.projection-disclaimer a')).toHaveAttribute('href', '/disclaimer');
    assert((await page.locator('.salary-toolbar label').first().boundingBox()).height < 120, 'Scenario control must not stretch into a tall empty mobile panel');
    assert(await page.locator('.page-content').evaluate(node => node.scrollWidth <= node.clientWidth));
    const region = page.locator('#salary-table .fv-table-scroll');
    await region.focus();
    await expect(region).toHaveCSS('outline-width', '3px');
    const summary = page.locator('.salary-projection-body .salary-summary-row').first();
    const disposable = summary.locator('.salary-disposable');
    await expect(disposable).toBeVisible();
    const visible = await disposable.boundingBox();
    const frame = await region.boundingBox();
    assert(visible.x >= frame.x && visible.x + visible.width <= frame.x + frame.width, 'Disposable income is visible without horizontal scrolling');
    if (width === 320) {
      const size = await page.locator('html').getAttribute('data-text-size');
      await page.locator('html').evaluate(node => {node.dataset.textSize = 'large';});
      const large = await disposable.boundingBox();
      const largeFrame = await region.boundingBox();
      assert(large.x >= largeFrame.x && large.x + large.width <= largeFrame.x + largeFrame.width, 'Disposable income stays visible at Large text size');
      await page.locator('html').evaluate((node, original) => {node.dataset.textSize = original;}, size);
    }
    const detail = summary.locator('[data-year-details]');
    await expect(detail).toHaveAttribute('aria-expanded', 'false');
    const key = await detail.getAttribute('aria-controls');
    await detail.focus();
    await page.keyboard.press('Enter');
    await expect(page.locator(`#${key}`)).toBeVisible();
    assert((await page.locator(`#${key} .salary-year-input`).first().boundingBox()).width >= 150, 'Expanded editable amounts retain their usable width');
    await detail.click();
    await expect(page.locator(`#${key}`)).toBeHidden();
    await page.screenshot({path: `${output}/${locale}-${width}-employment.png`, fullPage: true});
    await page.locator('#salary-save-as').click();
    const dialog = page.locator('#salary-save-as-backdrop');
    await expect(dialog).toHaveJSProperty('open', true);
    await expect(dialog.locator('[name="name"]')).toBeFocused();
    const close = page.locator('#salary-save-as-close');
    await expect(close).toHaveAttribute('data-icon-action', 'close');
    await close.focus();
    const tooltip = dialog.locator('[role="tooltip"]');
    await expect(tooltip).toHaveText(await close.getAttribute('aria-label'));
    await page.keyboard.press('Escape');
    await expect(tooltip).toHaveCount(0);
    await expect(dialog).toBeVisible();
    await page.keyboard.press('Shift+Tab');
    assert(await dialog.evaluate(node => node.contains(document.activeElement)));
    await page.keyboard.press('Escape');
    await expect(page.locator('#salary-save-as')).toBeFocused();
  }
  assert.deepEqual(rows(await read()), rows(original), 'Presentation and modal navigation preserve calculated and factual values');
  await page.locator('#salary-save-as').click();
  const name = `UX03I ${locale}`;
  await page.locator('#salary-save-as-form [name="name"]').fill(name);
  const cloneRequest = page.waitForRequest(request => request.url().endsWith('/clone'));
  await page.locator('#salary-save-as-form [type="submit"]').click();
  const clonePayload = (await cloneRequest).postDataJSON();
  assert.equal(clonePayload.settings, undefined, 'An unchanged clone must not resubmit or round saved assumptions');
  await expect(page.locator('#salary-save-as-backdrop')).toBeHidden();
  await expect(page.locator('#salary-message')).toContainText(name);
  const scenario = await page.locator('#salary-scenario').inputValue();
  assert.notEqual(Number(scenario), original.selected_scenario_id);
  assert.deepEqual(rows(await read(scenario)), rows(original), 'Cloning unchanged inputs preserves every annual amount');
  await page.locator(`#salary-tabs [data-person-key="${personId}"]`).click();
  await page.locator('[name="default_raise"]').fill('3');
  await page.locator('[name="retirement_date"]').fill('2027-07-01');
  await expect(page.locator('#salary-expense-form input').first()).toBeDisabled();
  await page.locator('#salary-save').click();
  await expect(page.locator('#salary-save')).toBeDisabled();
  await page.waitForFunction(() => document.querySelector('main').getAttribute('aria-busy') === 'false');
  const saved = (await read(scenario)).people.find(person => person.id === personId);
  assert.equal(saved.settings.retirement_date, '2027-07-01');
  assert.equal(saved.settings.default_raise, '0.03');
  assert(Number(saved.projection.find(row => row.year === 2027).gross_income) < Number(saved.projection.find(row => row.year === 2027).annual_salary_rate), 'Retirement year is prorated by the existing service');
  const details2027 = page.locator('[data-year-details="projection-2027"]');
  await details2027.click();
  const salary = page.locator('.salary-year-input[data-year="2027"][data-field="salary"]');
  const beforeDetailDraft = rows(await read(scenario));
  await salary.fill('120000');
  await page.locator('[data-year-cancel="2027"]').click();
  await expect(salary).toHaveValue(Number(saved.projection.find(row => row.year === 2027).annual_salary_rate).toFixed(2));
  assert.deepEqual(rows(await read(scenario)), beforeDetailDraft, 'Year Cancel never writes or recalculates');
  await salary.fill('123456.78');
  const draftInput = await salary.elementHandle();
  await page.setViewportSize({width: 1280, height: 1000});
  await page.setViewportSize({width: 320, height: 1000});
  assert(await salary.evaluate((node, original) => node === original, draftInput), 'Resize preserves the existing input node');
  await expect(salary).toHaveValue('123456.78');
  await details2027.click();
  await expect(salary).toBeHidden();
  await details2027.click();
  await expect(salary).toHaveValue('123456.78');
  assert.deepEqual(rows(await read(scenario)), beforeDetailDraft, 'Presentation toggles and resize never save or recalculate the draft');
  await page.locator('[data-year-details="projection-2026"]').click();
  const otherYear = page.locator('.salary-year-input[data-year="2026"][data-field="other_income"]');
  await otherYear.fill('2500');
  await page.locator('[name="default_raise"]').fill('4');
  await page.evaluate(() => {window.inlineYearSaveMarker = true;});
  await page.locator('[data-year-save="2027"]').click();
  await expect(page.locator('[data-year-message="2027"]')).toBeFocused();
  await expect(page.locator('[data-year-save="2027"]')).toBeDisabled();
  await expect(otherYear).toHaveValue('2500');
  await expect(page.locator('[name="default_raise"]')).toHaveValue('4');
  const onlyYearSaved = await read(scenario);
  assert.equal(onlyYearSaved.people.find(person => person.id === personId).settings.default_raise, '0.03');
  assert(!onlyYearSaved.people.find(person => person.id === personId).overrides.some(item => item.year === 2026 && item.other_income === '2500.00'));
  assert(await page.evaluate(() => window.inlineYearSaveMarker), 'Inline save does not navigate the page');
  await page.locator('#salary-discard').click();
  await expect(page.locator('[name="default_raise"]')).toHaveValue('3');
  await expect(page.locator('.salary-use-default[data-year="2027"][data-field="salary"]')).toBeVisible();
  assert.equal((await read(scenario)).people.find(person => person.id === personId).overrides.find(item => item.year === 2027).salary, '123456.78');
  const summaryHeights = await page.locator('.salary-projection-body .salary-summary-row').evaluateAll(rows => rows.map(row => row.getBoundingClientRect().height));
  assert(Math.max(...summaryHeights) - Math.min(...summaryHeights) < 2, 'Overrides do not make summary rows taller');
  const reset = page.locator('.salary-use-default[data-year="2027"][data-field="salary"]');
  await expect(reset).toHaveAttribute('data-icon-action', 'reset');
  assert.equal((await reset.innerText()).trim(), '');
  const resetBox = await reset.boundingBox();
  assert(resetBox.width >= 44 && resetBox.height >= 44);
  await reset.focus();
  await expect(page.locator('.fv-icon-tooltip')).toHaveText(await reset.getAttribute('aria-label'));
  await page.keyboard.press('Escape');
  await expect(page.locator('.fv-icon-tooltip')).toHaveCount(0);
  await expect(reset).toBeFocused();
  await reset.click();
  await page.locator('[data-year-save="2027"]').click();
  await expect(page.locator('.salary-use-default[data-year="2027"][data-field="salary"]')).toHaveCount(0);
  await page.locator('[data-person-key="household"]').click();
  await expect(page.locator('#salary-setup')).toBeHidden();
  await page.locator('#salary-expense-form [name="required_annual_amount"]').fill('45678.90');
  const householdDetails = page.locator('[data-year-details]').first();
  await expect(householdDetails).toBeEnabled();
  await householdDetails.click();
  await expect(page.locator('#salary-expense-form [name="required_annual_amount"]')).toHaveValue('45678.90');
  await page.locator('#salary-expense-save').click();
  await page.waitForFunction(() => document.querySelector('main').getAttribute('aria-busy') === 'false');
  assert.equal((await read(scenario)).expense_plan.required_annual_amount, '45678.90');
  assert.deepEqual(rows(await read(original.selected_scenario_id)), rows(original), 'Draft and spending saves never mutate the original scenario');
  // Full storage precision must remain valid through every browser editor.
  await page.locator(`[data-person-key="${personId}"]`).click();
  const defaultRaise = page.locator('[name="default_raise"]');
  await defaultRaise.fill('2.5123');
  assert(await defaultRaise.evaluate(node => node.checkValidity()));
  await page.locator('#salary-save').click();
  await expect(page.locator('#salary-save')).toBeDisabled();
  await page.waitForFunction(() => document.querySelector('main').getAttribute('aria-busy') === 'false');
  await expect(defaultRaise).toHaveValue('2.5123');
  if (!(await page.locator('.salary-year-input[data-year="2027"]').first().isVisible())) await page.locator('[data-year-details="projection-2027"]').click();
  const fractionalRaise = page.locator('[data-year="2027"][data-field="raise_rate"]');
  await expect(fractionalRaise).toHaveValue('2.5123');
  assert(await fractionalRaise.evaluate(node => node.checkValidity()), 'Inherited fractional raise must not block unrelated annual edits');
  await page.locator('[data-year="2027"][data-field="other_income"]').fill('1234.56');
  await page.locator('[data-year-save="2027"]').click();
  await expect(page.locator('[data-year-save="2027"]')).toBeDisabled();
  await expect(fractionalRaise).toHaveValue('2.5123');
  await fractionalRaise.fill('1.5678');
  await page.locator('[data-year-save="2027"]').click();
  await expect(page.locator('[data-year-save="2027"]')).toBeDisabled();
  await expect(fractionalRaise).toHaveValue('1.5678');
  const fractionalSaved = (await read(scenario)).people.find(person => person.id === personId);
  assert.equal(fractionalSaved.settings.default_raise, '0.025123');
  assert.equal(fractionalSaved.overrides.find(row => row.year === 2027).raise_rate, '0.015678');
  assert.equal(fractionalSaved.overrides.find(row => row.year === 2027).other_income, '1234.56');
  await page.locator('[data-person-key="household"]').click();
  for (const [field, value] of [['required_annual_growth', '1.2345'], ['discretionary_annual_growth', '2.3456']]) {
    const input = page.locator(`#salary-expense-form [name="${field}"]`);
    await input.fill(value);
    assert(await input.evaluate(node => node.checkValidity()));
  }
  await page.locator('#salary-expense-save').click();
  await page.waitForFunction(() => document.querySelector('main').getAttribute('aria-busy') === 'false');
  await expect(page.locator('[name="required_annual_growth"]')).toHaveValue('1.2345');
  await expect(page.locator('[name="discretionary_annual_growth"]')).toHaveValue('2.3456');
  assert.equal((await read(scenario)).expense_plan.required_annual_growth, '0.012345');
  assert.equal((await read(scenario)).expense_plan.discretionary_annual_growth, '0.023456');
  const fail = route => route.fulfill({status: 503, contentType: 'application/json', body: JSON.stringify({error: 'Synthetic unavailable projection'})});
  await page.route('**/api/salary-projection?*', fail);
  await page.locator('#salary-view').click();
  await expect(page.locator('#salary-message')).toHaveAttribute('role', 'alert');
  await expect(page.locator('#salary-table table')).toHaveCount(0);
  await page.unroute('**/api/salary-projection?*', fail);
  await page.locator('#salary-message button').click();
  await expect(page.locator('#salary-table table')).toBeVisible();
  assert(!(await page.locator('main').innerText()).includes('⟦'));
}
